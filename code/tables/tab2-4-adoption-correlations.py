# Table 2: correlations between each exposure measure and reported generative-AI adoption, with the R-squared of the respondent-weighted
# regression. Same data and weights as the appendix adoption
# regressions (code/tables/tabA-measurement.py): occ_measures.csv, occupations with at least 20 respondents in the Real-Time Population Survey
# (Bick et al.), weighted by respondent counts. Run from anywhere: python3 code/tables/tab2-4-adoption-correlations.py
import sys as _sys, pathlib as _pl; _sys.path.insert(0, str(_pl.Path(__file__).resolve().parents[1])); from paths import *   # repository-relative paths (code/paths.py)
import pandas as pd, numpy as np, statsmodels.api as sm
om=pd.read_csv(PIPELINE/"occ_measures.csv")
ROWS=[("Exposure levels",[("ensemble3_s1","Stage 1 (pre-generative machine learning)"),("ensemble3_s2","Stage 2 (chatbots)"),("ensemble3_s3","Stage 3 (reasoning models)"),("ensemble3_s4","Stage 4 (agents)")]),
      ("Exposure changes",[("d_ens_s4_s1","Stage 1 to 4"),("d_ens_s3_s1","Stage 1 to 3"),("d_ens_s3_s2","Stage 2 to 3")]),
      ("Existing measures",[("dv_rating_gamma","Eloundou et al.\\ (2024), $\\zeta$"),("felten_aioe","Felten et al.\\ (2023), language-modeling exposure")])]
def wcorr(x,y,w):
    mx,my=np.average(x,weights=w),np.average(y,weights=w); cov=np.average((x-mx)*(y-my),weights=w); return cov/np.sqrt(np.average((x-mx)**2,weights=w)*np.average((y-my)**2,weights=w))
def wrank(x,w):   # weighted Spearman as the weighted correlation of ranks
    return pd.Series(x).rank().values
out=[]; N=None
for head,items in ROWS:
    out.append("\\multicolumn{4}{@{}l}{\\emph{"+head+"}} \\\\")
    for col,lab in items:
        d=om.dropna(subset=["rps_adoption","rps_n",col]); d=d[d.rps_n>=20]; N=N or len(d)
        y=100*d.rps_adoption.values; x=d[col].values; w=d.rps_n.values
        z=(x-np.average(x,weights=w))/np.sqrt(np.average((x-np.average(x,weights=w))**2,weights=w))
        f=sm.WLS(y,sm.add_constant(z),weights=w).fit(cov_type="HC1")
        pe=wcorr(x,y,w); sp=wcorr(wrank(x,w),wrank(y,w),w)
        def fmt(v): s=f"{v:.2f}"; return s.replace("-","$-$")
        out.append(f"{lab} & {fmt(pe)} & {fmt(sp)} & {pe**2:.2f} \\\\")
        print(f"{lab[:44]:46s} n={len(d)} coef {f.params[1]:6.2f} ({f.bse[1]:.2f})  pearson {pe:5.2f}  spearman {sp:5.2f}  R2 {f.rsquared:.2f}")
    out.append("\\addlinespace")
out=out[:-1]
tex=["% Table 1: correlations between each measure and reported adoption, with the bivariate regression coefficient and R-squared.",
"% Generated by code/tables/tab2-4-adoption-correlations.py from occ_measures.csv. Do not edit by hand.",
"\\begin{table}[htbp]\n\\centering\n\\begin{threeparttable}",
"\\caption{Reported generative-AI adoption and each exposure measure}",
"\\label{tab:adoption}",
"\\begin{spacing}{1}",
"\\begin{tabular}{@{}lccc@{}}\n\\toprule",
"Measure & Pearson & Spearman & $R^{2}$ \\\\\n\\midrule"]+out+["\\bottomrule\n\\end{tabular}\n\\end{spacing}",
"\\begin{tablenotes}\\notesize",
f"\\item Notes: Adoption is the share of workers in an occupation who report using generative AI at work, in percentage points, from four waves of the Real-Time Population Survey of \\citet{{bick2026work}}, August 2025 to May 2026; the sample is the {N} occupations with at least 20 respondents and an exposure score. Pearson is the correlation weighted by respondent counts, Spearman the weighted correlation of ranks, and $R^{{2}}$ the squared Pearson correlation, i.e., the share of the variation in adoption that the measure explains.",
"\\end{tablenotes}\n\\end{threeparttable}\n\\end{table}"]
