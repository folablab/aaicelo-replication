# Appendix Table A.5: a worked example, one task through every step.
# Inputs (data/scoring/task_7359/): the Prompt 0 decomposition of task 7359 (p0_7359.json) and the three models' subtask ratings
# for it (claude/, gemini_flash_lite/, gpt_luna/: p{a,b,c}_7359.json), copied from the scoring project's output files.
# The task-level ratings and composites computed here are checked against data/scoring/master_task_scores.csv.
# Run from anywhere: python3 code/tables/tabA-worked-example.py   (writes output/tables/tabA-worked-example.tex)
