O = str(SCORING / "task_7359"); HERE = TABLES
TASK = 7359
MODELS = {"claude": f"{O}/claude", "gemini_flash_lite": f"{O}/gemini_flash_lite", "gpt_luna": f"{O}/gpt_luna"}
STAGES = ["stage_1", "stage_2", "stage_3", "stage_4"]
p0 = json.load(open(f"{O}/p0_{TASK}.json"))
subs = p0["task_decomposition"]; shares = [s["pct_of_total_time"] / 100 for s in subs]; assert abs(sum(shares) - 1) < 1e-9
SHORT = {1: "Gather and review the client's documents", 2: "Compute taxable income, deductions, and credits", 3: "Enter the data into tax software",
         4: "Review the completed return", 5: "Communicate with the client", 6: "Authorize the return for submission"}

def ratings(model):
    """Per subtask and stage: A (constraint-adjusted percent of time saved), B (1 if AI completes it alone), C (1 if people keep an advantage),
    made monotone across stages as in Appendix A.5: A and B may not fall, C may not rise."""
    base = MODELS[model]
    a = json.load(open(f"{base}/pa_{TASK}.json"))["subtask_assessments"]
    b = json.load(open(f"{base}/pb_{TASK}.json"))["subtask_assessments"]
    c = json.load(open(f"{base}/pc_{TASK}.json"))["subtask_assessments"]
    A, B, C = [], [], []
    for i in range(len(subs)):
        ra = [min(a[i]["time_savings_by_stage"][s]["feasible"], a[i]["time_savings_by_stage"][s]["technical"]) for s in STAGES]
        rb = [int(bool(b[i]["ai_can_complete_independently"][s]["feasible"])) for s in STAGES]
        rc = [int(bool(c[i]["human_has_advantage"][s])) for s in STAGES]
        for k in range(1, 4):
            ra[k] = max(ra[k], ra[k - 1]); rb[k] = max(rb[k], rb[k - 1]); rc[k] = min(rc[k], rc[k - 1])
        A.append(ra); B.append(rb); C.append(rc)
    return A, B, C

def task_level(A, B, C):
    At = [sum(w * A[i][k] for i, w in enumerate(shares)) for k in range(4)]
    Bt = [sum(w * 100 * B[i][k] for i, w in enumerate(shares)) for k in range(4)]
    Ct = [sum(w * 100 * C[i][k] for i, w in enumerate(shares)) for k in range(4)]
    E = [(At[k] + Bt[k] + 100 - Ct[k]) / 3 for k in range(4)]
    return At, Bt, Ct, E

master = pd.read_csv(SCORING / "master_task_scores.csv"); row = master[master.task_id == TASK].iloc[0]
R = {m: ratings(m) for m in MODELS}; T = {m: task_level(*R[m]) for m in MODELS}
for m in MODELS:   # the task-level numbers must reproduce the master file (tolerance: its one-decimal rounding)
    At, Bt, Ct, E = T[m]
    for k in range(4):
        assert abs(At[k] - row[f"{m}_a_s{k+1}_feasible"]) < 0.06, (m, k, At[k], row[f"{m}_a_s{k+1}_feasible"])
        assert abs(Bt[k] - row[f"{m}_b_s{k+1}_feasible"]) < 0.06, (m, k, Bt[k], row[f"{m}_b_s{k+1}_feasible"])
        assert abs(Ct[k] - row[f"{m}_c_s{k+1}_human_advantage"]) < 0.06, (m, k, Ct[k], row[f"{m}_c_s{k+1}_human_advantage"])
        assert abs(E[k] - row[f"{m}_composite_s{k+1}"]) < 0.06, (m, k, E[k], row[f"{m}_composite_s{k+1}"])
ens = [sum(T[m][3][k] for m in MODELS) / 3 for k in range(4)]
for k in range(4): assert abs(ens[k] - row[f"ensemble3_composite_s{k+1}"]) < 0.06, (k, ens[k], row[f"ensemble3_composite_s{k+1}"])
print("task-level ratings and composites reproduce master_task_scores.csv for the three models and the ensemble")

