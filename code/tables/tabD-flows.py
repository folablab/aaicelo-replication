# Appendix Table D.5 (tab:flows): three-year changes in the monthly flows of workers into and out of occupations,
# by age and for the under-30 degree split. Run from anywhere:
#   python3 code/tables/tabD-flows.py          (writes output/tables/tabD-flows.tex)
# Input: data/pipeline/flow_counts.csv, written by the authors' pipeline (Stata script
# 150_entrant_exit_counts.do, not included because it reads the CPS microdata) from month-link flow panels
# (consecutive CPS interviews linked on the IPUMS person identifier, validated on sex and age) and the group panels. The regression is Eq. (group) of the paper with a flow count in place of the log count of workers:
# the three-year difference, 2026Q1 vs 2023Q1 and 2026Q2 vs 2023Q2 stacked with a period effect, the standardized stage-1 to
# stage-4 change in exposure, the twelve base-period composition shares, base-period group employment weights, standard
# errors clustered by occupation. The outcome is the change in the monthly number of movers per 100 base-period workers of
# the group in the occupation, so that cells with no movers in a quarter stay in the sample; the last column is the net of
# entrants from all sources minus exits to all destinations on the cells where both are observed. The levels of the flows are
# not tabulated; the lvl_mean column of the CSV holds them. Movers are counted as the
# month-link rate times the group's employment in the occupation-quarter.
import sys as _sys, pathlib as _pl; _sys.path.insert(0, str(_pl.Path(__file__).resolve().parents[1])); from paths import *   # repository-relative paths (code/paths.py)
import datetime, pandas as pd
R = PIPELINE / "flow_counts.csv"
d = pd.read_csv(R)
d = d[(d.treat == "s41") & (d.controls == 1)]
today = datetime.date.today().strftime("%B %-d, %Y")

def star(p): return "\\textsuperscript{***}" if p < .01 else "\\textsuperscript{**}" if p < .05 else "\\textsuperscript{*}" if p < .1 else ""
def cell(r): return f"{r.b:.2f}{star(r.p)} ({r.se:.2f})"
def fmt(x): return f"{x:.2f}".replace("-", "$-$")

COLS = ["dc_in_nonemp", "dc_in_occ", "dc_in_any", "dc_out_nonemp", "dc_out_unemp", "dc_out_occ", "dc_out_any", "dc_net"]
ROWS = [("u30", "Under 30"), ("a3049", "30 to 49"), ("a50p", "50 to 64"), ("all", "All workers"),
        (None, r"\emph{Under 30, by education}"),
        ("u30_ltBA", r"\quad Less than a bachelor's degree"), ("u30_BAp", r"\quad Bachelor's degree or more")]
WIN = [("ld3_head", "A. Headline window: 2026Q1--Q2 vs. 2023Q1--Q2"), ("ld3_plac", "B. Placebo window: 2021Q4--2022Q3 vs. 2018Q4--2019Q3")]

def row(win, g):
    s = d[(d.window == win) & (d.group == g)].set_index("outcome")
    b = " & ".join(f"{s.loc[c].b:.2f}{star(s.loc[c].p)}".replace("-", "$-$") for c in COLS)
    se = " & ".join(f"({s.loc[c].se:.2f})" for c in COLS)
    return b, se

def nrange(win):
    s = d[(d.window == win) & (d.outcome.isin(COLS))]
    return int(s.N.min()), int(s.N.max())

def lvl(g, c):
    return d[(d.window == "ld3_head") & (d.group == g)].set_index("outcome").loc[c].lvl_mean

lines = []
lines.append(f"% Appendix Table: flows of workers into and out of occupations, by group. Generated by code/tables/tabD-flows.py")
lines.append("% from replication/flow_counts.csv (pipeline script 150_entrant_exit_counts.do). Do not edit by hand.")
lines.append(r"\begin{table}[htbp]")
lines.append(r"\centering")
lines.append(r"\begin{threeparttable}")
lines.append(r"\caption{Three-year changes in the monthly flows of workers into and out of occupations, by age and by age and education}")
lines.append(r"\label{tab:flows}")
lines.append(r"\setstretch{1}\fontsize{8.3}{9.8}\selectfont\setlength{\tabcolsep}{2.5pt}")
lines.append(r"\begin{tabular}{@{}l*{8}{c}@{}}")
lines.append(r"\toprule")
lines.append(r" & \multicolumn{3}{c}{Entrants} & \multicolumn{4}{c}{Exits} & \\")
lines.append(r"\cmidrule(lr){2-4}\cmidrule(lr){5-8}")
lines.append(r" & \shortstack{From\\non-\\employment} & \shortstack{From\\another\\occupation} & \shortstack{All\\sources} & \shortstack{To\\non-\\employment} & \shortstack{To\\unem-\\ployment} & \shortstack{To\\another\\occupation} & \shortstack{All\\destinations} & \shortstack{Net:\\entrants\\minus exits} \\")
lines.append(r"\midrule")
for i, (win, title) in enumerate(WIN):
    lines.append(rf"\multicolumn{{9}}{{@{{}}l}}{{\emph{{{title}}}}} \\")
    for g, lab in ROWS:
        if g is None:
            lines.append(f"{lab} & " + " & ".join([""] * len(COLS)) + " \\\\")
            continue
        b, se = row(win, g)
        lines.append(f"{lab} & {b} \\\\")
        lines.append(f" & {se} \\\\")
    if i == 0: lines.append(r"\addlinespace")
lines.append(r"\bottomrule")
lines.append(r"\end{tabular}")
nh, nph = nrange("ld3_head"); npl, nppl = nrange("ld3_plac")
u = {c: lvl("u30", c) for c in COLS}
lines.append(r"\begin{tablenotes}\notesize")
lines.append(r"\item Notes: Each cell is the coefficient of Eq.~(\ref{eq:group}) with a monthly flow of workers in place of the log count of workers: the three-year difference, per standard deviation of the stage-1 to stage-4 change in exposure, in the number of workers entering or leaving the occupation each month per 100 base-period workers of the group in the occupation, with the twelve base-period composition shares, base-period group employment weights, a period effect, and standard errors clustered by occupation in parentheses. "
             r"Movers are identified by linking consecutive monthly interviews of the same respondent in the CPS rotating panel. Non-employment is unemployment plus being out of the labor force. An entrant from non-employment was unemployed or out of the labor force in the previous month, and an entrant from another occupation was employed under a different occupation code; exits are the reverse, and exits to unemployment are the part of exits to non-employment whose destination is unemployment. The last column is the change in entrants from all sources minus the change in exits to all destinations, estimated on the cells where both are observed. "
             r"The monthly rate from the linked sample is multiplied by the group's employment in the occupation and quarter to obtain the count, so that quarters with no movers remain in the sample. "
             r"Moves between occupation codes include coding noise: about 7 percent of linked workers employed in both months carry a different occupation code, against 2 percent among those who report the same employer, so the non-employment columns are the cleaner measure. "
             rf"A net coefficient of $-$0.37 in the first row cumulates over 36 months to a decline of about 13 percent, against the 8.20 log point decline in the number of workers under 30 over the same window (Table~\ref{{tab:cell_fd_main_4}}), but its standard error is wide. "
             rf"$N$ is between {nh:,} and {nph:,} occupation-quarter cells in Panel A and between {npl:,} and {nppl:,} in Panel B. "
             r"\textsuperscript{*} $p<0.10$, \textsuperscript{**} $p<0.05$, \textsuperscript{***} $p<0.01$.")
lines.append(r"\end{tablenotes}")
lines.append(r"\end{threeparttable}")
lines.append(r"\end{table}")
open(TABLES / "tabD-flows.tex", "w").write("\n".join(lines) + "\n")
print(open(TABLES / "tabD-flows.tex").read())
