#!/usr/bin/env python3
"""tabB-crosswalk.py: Appendix B tables on the O*NET to census crosswalk.
Reads the crosswalk files (data/crosswalks/) and the derived measures (data/pipeline/), writes
output/tables/tabB-crosswalk.tex (Table B.1: the mapping, step by step, and the harmonized codes by how many
2018 codes feed them) and tables/tabB-unscored.tex (Table B.2: the 22 harmonized codes without a score).
Run from anywhere: python3 code/tables/tabB-crosswalk.py"""
import sys as _sys, pathlib as _pl; _sys.path.insert(0, str(_pl.Path(__file__).resolve().parents[1])); from paths import *   # repository-relative paths (code/paths.py)
import pandas as pd, numpy as np
from pathlib import Path
HERE = TABLES; XW = CROSSWALKS; A = PIPELINE; T = SCORING / "master_task_scores.csv"
oc = pd.read_stata(XW / "onet_to_cps_crosswalk_cleaned.dta")
x10 = pd.read_stata(XW / "occ_to_occ2010_2020_2026.dta", convert_categoricals=False); x10 = x10[x10.occ2010 != 9999].copy(); x10["occ2010"] = x10.occ2010.astype(int)
t18 = pd.read_csv(A / "occ_measures.csv"); t18["cps_code"] = pd.to_numeric(t18.cps_code, errors="coerce")
t10 = pd.read_stata(A / "occ2010_measures.dta", convert_categoricals=False); t10["occ2010"] = t10.occ2010.astype(int)
panel = pd.read_stata(A / "occ2010_quarter_panel.dta", convert_categoricals=False)
tasks = pd.read_csv(T, usecols=lambda c: c in ("task_id", "onet_code"))
# ---- step counts
n_task = tasks.task_id.nunique(); n_onet_scored = tasks.onet_code.nunique()
n_onet_xw = oc.onet_code.nunique(); n_soc = oc.soc_code.nunique(); n_cps = oc.cps_code.nunique()
n_cps_scored = int(t18.d_ens_s4_s1.notna().sum()); n_cps_in_x10 = x10.cps_code.nunique(); n_occ2010_xw = x10.occ2010.nunique()
n_panel = t10.occ2010.nunique(); scored = t10[t10.d_ens_s4_s1.notna()].occ2010; n_scored = len(scored)
# ---- harmonized codes by number of 2018 codes feeding them (scored codes), person-month shares 2020-2026
g = x10[x10.occ2010.isin(scored)].groupby("occ2010").agg(n18=("cps_code", "nunique"), freq=("_freq", "sum")).reset_index()
tot = g.freq.sum(); bins = [("One 2018 code", g.n18 == 1), ("Two 2018 codes", g.n18 == 2), ("Three or more 2018 codes", g.n18 >= 3)]
rows = [(lab, int(m.sum()), 100 * g.freq[m].sum() / tot) for lab, m in bins]
# ---- within-code range of the S4-S1 change among many-to-one codes; agreement on one-to-one codes
m = x10.merge(t18[["cps_code", "d_ens_s4_s1"]], on="cps_code").merge(t10[["occ2010", "d_ens_s4_s1"]], on="occ2010", suffixes=("_18", "_10"))
m = m[m.occ2010.isin(scored)]
many = m.groupby("occ2010").agg(n=("cps_code", "nunique"), rng=("d_ens_s4_s1_18", lambda s: s.max() - s.min())); many = many[many.n > 1]
one = m[m.occ2010.isin(g.occ2010[g.n18 == 1])].dropna(subset=["d_ens_s4_s1_18", "d_ens_s4_s1_10"])
corr_one = one[["d_ens_s4_s1_18", "d_ens_s4_s1_10"]].corr().iloc[0, 1]; maxdiff_one = (one.d_ens_s4_s1_18 - one.d_ens_s4_s1_10).abs().max()
print(f"tasks {n_task}; O*NET occupations with tasks {n_onet_scored}; in crosswalk {n_onet_xw}; SOC {n_soc}; 2018 census codes {n_cps} (scored {n_cps_scored}); "
      f"2018 codes in the harmonized crosswalk {n_cps_in_x10} -> {n_occ2010_xw} harmonized; panel {n_panel}, scored {n_scored}")
print(rows, f"many-to-one median range {many.rng.median():.1f}, p90 {many.rng.quantile(.9):.1f}; one-to-one corr {corr_one:.4f}, max abs diff {maxdiff_one:.4f}")
L = []
L.append(r"""% Generated by code/tables/tabB-crosswalk.py from the crosswalk files. Do not edit by hand.
\begin{table}[htbp]
\centering
\caption{From O*NET occupations to harmonized census codes}
\label{tab:crosswalk}
\begin{threeparttable}
\begin{tabular}{@{}>{\raggedright\arraybackslash}p{9.6cm}rr@{}}
\toprule
\multicolumn{3}{@{}l}{\textit{A. The mapping, step by step}} \\
\midrule
& Units & \\
\midrule""")
L.append(f"O*NET task statements & {n_task:,} & \\\\")
L.append(f"O*NET-SOC 2019 occupations with task statements & {n_onet_scored} & \\\\")
L.append(f"SOC 2018 codes & {n_soc} & \\\\")
L.append(f"2018 census occupation codes & {n_cps} & \\\\")
L.append(f"\\quad with an exposure score & {n_cps_scored} & \\\\")
L.append(f"Harmonized (OCC2010) codes in the 2017--2026 panel & {n_panel} & \\\\")
L.append(f"\\quad with an exposure score (estimation sample) & {n_scored} & \\\\")
L.append(r"""\midrule
\multicolumn{3}{@{}l}{\textit{B. Harmonized codes by the number of 2018 codes that feed them}} \\
\midrule
& Codes & Share of person-months \\
\midrule""")
for lab, n, sh in rows: L.append(f"{lab} & {n} & {sh:.1f} \\\\")
L.append(r"\midrule")
L.append(f"Correlation of the S4--S1 change across the two files, one-to-one codes & {corr_one:.3f} & \\\\")
L.append(f"Median within-code range of the S4--S1 change, many-to-one codes & {many.rng.median():.1f} & \\\\")
L.append(f"90th percentile of that range & {many.rng.quantile(.9):.1f} & \\\\")
L.append(r"""\bottomrule
\end{tabular}
\begin{tablenotes}[flushleft]\notesize
\item Notes: Panel A counts the units at each step of the mapping from O*NET task statements to the harmonized census codes of the estimation sample. Panel B classifies the harmonized codes of the estimation sample by how many 2018 census codes map into them; shares are of CPS person-months from January 2020 to June 2026, the period in which the 2018 codes are in use. The S4--S1 change is the change in the exposure score from stage 1 to stage 4, in points; the within-code range is the difference between the largest and the smallest change among the 2018 codes that feed one harmonized code.
\end{tablenotes}
\end{threeparttable}
\end{table}""")
(HERE / "tabB-crosswalk.tex").write_text("\n".join(L) + "\n")
# ---- Table B.2: the unscored harmonized codes
labs = pd.read_csv(PIPELINE / "occ2010_labels.csv").set_index("occ2010").title.to_dict()   # the IPUMS OCC2010 labels (code/prepare/occ2010_labels.py)
miss = sorted(set(t10.occ2010[t10.d_ens_s4_s1.isna()])); emp_tot = panel.emp.sum()
def q(t): t = pd.Timestamp(t); return f"{t.year}Q{(t.month - 1) // 3 + 1}"
U = []
for c in miss:
    s = panel[panel.occ2010 == c]; U.append((c, labs.get(c, ""), q(s.qdate.min()), q(s.qdate.max()), 100 * s.emp.sum() / emp_tot))
resid = [u for u in U if u[3] == "2026Q2"]; ended = [u for u in U if u[3] != "2026Q2"]
print(f"unscored: {len(miss)} = {len(resid)} residual categories + {len(ended)} codes ending in 2019; employment share {sum(u[4] for u in U):.2f} percent")
def esc(s): return s.replace("&", r"\&").replace("%", r"\%")
L = [r"""% Generated by code/tables/tabB-crosswalk.py. Do not edit by hand.
\begin{table}[htbp]
\centering
\caption{Harmonized codes without an exposure score}
\label{tab:unscored}
\begin{threeparttable}
\footnotesize
\begin{tabular}{@{}l>{\raggedright\arraybackslash}p{6.2cm}cr@{}}
\toprule
Code & Title & Quarters in the panel & Share of employment (percent) \\
\midrule
\multicolumn{4}{@{}l}{\textit{A. Residual categories with no O*NET counterpart}} \\"""]
for c, l, a, b, sh in resid: L.append(f"{c} & {esc(l.capitalize())} & {a}--{b} & {sh:.2f} \\\\")
L.append(r"\midrule" + "\n" + r"\multicolumn{4}{@{}l}{\textit{B. Codes that end with the 2020 reclassification}} \\")
for c, l, a, b, sh in ended: L.append(f"{c} & {esc(l.capitalize())} & {a}--{b} & {sh:.2f} \\\\")
L.append(r"\midrule" + f"\nAll {len(miss)} codes & & & {sum(u[4] for u in U):.2f} \\\\")
L.append(r"""\bottomrule
\end{tabular}
\begin{tablenotes}[flushleft]\notesize
\item Notes: The harmonized (IPUMS OCC2010) codes that appear in the 2017Q1--2026Q2 occupation-by-quarter panel but carry no exposure score. Titles are the IPUMS labels. The share of employment is the code's CPS-weighted employment summed over the quarters it appears in, as a share of total employment over all 38 quarters. Panel A lists residual ``all other'' categories, for which O*NET has no occupation; Panel B lists codes that the 2018 census classification discontinued, so that no 2018 code maps into them and they do not appear after 2019Q4.
\end{tablenotes}
\end{threeparttable}
\end{table}""")
(HERE / "tabB-unscored.tex").write_text("\n".join(L) + "\n"); print("wrote tabB-crosswalk.tex and tabB-unscored.tex")
